type MessageTree = typeof messages.zh;

const lookup = (tree: unknown, key: string): unknown => {
  return key.split('.').reduce<unknown>((current, part) => {
    if (current && typeof current === 'object' && part in current) {
      return (current as Record<string, unknown>)[part];
    }
    return undefined;
  }, tree);
};

const interpolate = (value: string, params?: Record<string, string | number>) => {
  if (!params) return value;
  return value.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? ''));
};

export const useI18n = () => {
  const t = (key: string, params?: Record<string, string | number>) => {
    const value = lookup(messages[language.value], key) ?? lookup(messages.zh, key);
    return typeof value === 'string' ? interpolate(value, params) : key;
  };

  const tm = <T = unknown>(key: string): T => {
    const value = lookup(messages[language.value], key) ?? lookup(messages.zh, key);
    return value as T;
  };

  const setLanguage = (value: Language) => {
    language.value = value;
  };

  return {
    language,
    isChinese: computed(() => language.value === 'zh'),
    setLanguage,
    t,
    tm,
  };
};

watchEffect(() => {
  if (typeof window !== 'undefined') {
    window.localStorage.setItem(STORAGE_KEY, language.value);
  }
  if (typeof document !== 'undefined') {
    document.documentElement.lang = language.value === 'zh' ? 'zh-CN' : 'en';
    document.title = messages[language.value].common.brand;
  }
});

